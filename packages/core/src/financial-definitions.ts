export const financialMetric = (id: string) =>
  financialMetrics.find((m) => m.id === id);
export function financialUnit(id: string) {
  const format = financialMetric(id)?.format;
  return format === "shares"
    ? "shares"
    : format === "perShare"
      ? "USD/shares"
      : "USD";
}
